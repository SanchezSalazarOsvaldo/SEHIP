-- una migración cambia la base que ya está en uso sin perder datos y va dentro de BEGIN ... COMMIT: si algo falla no se aplica nada.
--Si se borrara la base y se creara de nuevo, se perderían cuentas, proyectos y reportes.
-- =====================================================================
-- SEHIP · Migración a la base normalizada 
-- Ejecutar UNA sola vez en el SQL Editor de Supabase sobre la base que ya está en uso. Conserva todos los
-- datos (usuarios, proyectos, simulaciones, reportes e incidencias). Va dentro de una transacción: si algo
-- falla, no se aplica ningún cambio.
-- Después de esta, ejecutar migracion_datos_esenciales.sql
--
-- Qué cambia:
--   1. Catálogos tipo_incidencia, nivel_agua y tipo_obra: los textos repetidos se reemplazan por llaves.
--   2. proyecto deja de guardar resultados calculados (superficie total, coeficiente, intensidad y caudal).
--   3. simulacion_mitigacion deja de guardar resultados calculados (distancia, eficiencia, caudales).
--   4. alcaldia pierde porcentaje_absorcion (no se usaba; la app lo calcula con Cp).
--   5. Nueva tabla proyecto_ingeniero para que varios ingenieros trabajen un mismo proyecto.
-- =====================================================================
BEGIN;

-- 1. Catálogos ---------------------------------------------------------
CREATE TABLE tipo_incidencia (
    id_tipo_incidencia  SMALLINT    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre              VARCHAR(30) NOT NULL,
    CONSTRAINT uq_tipo_incidencia_nombre UNIQUE (nombre)
);
CREATE TABLE nivel_agua (
    id_nivel_agua  SMALLINT    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre         VARCHAR(10) NOT NULL,
    CONSTRAINT uq_nivel_agua_nombre UNIQUE (nombre)
);
CREATE TABLE tipo_obra (
    id_tipo_obra  SMALLINT    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre        VARCHAR(30) NOT NULL,
    CONSTRAINT uq_tipo_obra_nombre UNIQUE (nombre)
);
INSERT INTO tipo_incidencia (nombre) VALUES ('Encharcamiento'), ('Inundación'), ('Coladera obstruida');
INSERT INTO nivel_agua (nombre) VALUES ('Bajo'), ('Medio'), ('Alto');
INSERT INTO tipo_obra (nombre) VALUES ('Pozo de Infiltración'), ('Tanque de Tormenta'), ('Jardín de Lluvia');

-- punto_critico: tipo y nivel_agua (texto) pasan a ser llaves de los catálogos.
ALTER TABLE punto_critico ADD COLUMN id_tipo_incidencia SMALLINT, ADD COLUMN id_nivel_agua SMALLINT;
UPDATE punto_critico p SET id_tipo_incidencia = t.id_tipo_incidencia FROM tipo_incidencia t WHERE t.nombre = p.tipo;
UPDATE punto_critico p SET id_nivel_agua = n.id_nivel_agua FROM nivel_agua n WHERE n.nombre = p.nivel_agua;
ALTER TABLE punto_critico
    ALTER COLUMN id_tipo_incidencia SET NOT NULL,
    ADD CONSTRAINT fk_punto_tipo  FOREIGN KEY (id_tipo_incidencia) REFERENCES tipo_incidencia (id_tipo_incidencia),
    ADD CONSTRAINT fk_punto_nivel FOREIGN KEY (id_nivel_agua) REFERENCES nivel_agua (id_nivel_agua),
    DROP CONSTRAINT IF EXISTS ck_punto_tipo,
    DROP CONSTRAINT IF EXISTS ck_punto_nivel,
    DROP COLUMN tipo,
    DROP COLUMN nivel_agua;
-- Las columnas nuevas quedan junto a las demás al consultar con SELECT *; el orden físico no importa.

-- 2. proyecto: solo datos de entrada ----------------------------------------
ALTER TABLE proyecto
    DROP CONSTRAINT IF EXISTS ck_proyecto_superficies,
    DROP CONSTRAINT IF EXISTS ck_proyecto_total,
    DROP CONSTRAINT IF EXISTS ck_proyecto_coeficiente,
    DROP CONSTRAINT IF EXISTS ck_proyecto_intensidad,
    DROP CONSTRAINT IF EXISTS ck_proyecto_intensidad_periodo,
    DROP CONSTRAINT IF EXISTS ck_proyecto_caudal,
    DROP CONSTRAINT IF EXISTS ck_proyecto_estado,
    DROP COLUMN superficie_total,
    DROP COLUMN coeficiente_c,
    DROP COLUMN intensidad_mm_h,
    DROP COLUMN caudal_pico;
ALTER TABLE proyecto
    ADD CONSTRAINT fk_proyecto_intensidad FOREIGN KEY (id_alcaldia, periodo_retorno)
        REFERENCES intensidad_lluvia (id_alcaldia, periodo_retorno),
    ADD CONSTRAINT ck_proyecto_superficies CHECK (
        (superficie_permeable IS NULL AND superficie_impermeable IS NULL)
        OR (superficie_permeable BETWEEN 0 AND 1000000 AND superficie_impermeable BETWEEN 0 AND 1000000
            AND superficie_permeable + superficie_impermeable BETWEEN 0.01 AND 1000000)),
    ADD CONSTRAINT ck_proyecto_estado CHECK (
        estado = 'En proceso' OR (superficie_permeable IS NOT NULL AND periodo_retorno IS NOT NULL));

-- 3. simulacion_mitigacion: solo la obra propuesta ----------------------------
ALTER TABLE simulacion_mitigacion ADD COLUMN id_tipo_obra SMALLINT;
UPDATE simulacion_mitigacion s SET id_tipo_obra = t.id_tipo_obra FROM tipo_obra t WHERE t.nombre = s.tipo_obra;
ALTER TABLE simulacion_mitigacion
    ALTER COLUMN id_tipo_obra SET NOT NULL,
    ADD CONSTRAINT fk_simulacion_tipo FOREIGN KEY (id_tipo_obra) REFERENCES tipo_obra (id_tipo_obra),
    DROP CONSTRAINT IF EXISTS ck_simulacion_tipo,
    DROP CONSTRAINT IF EXISTS ck_simulacion_retencion,
    DROP CONSTRAINT IF EXISTS ck_simulacion_eficiencia,
    DROP CONSTRAINT IF EXISTS ck_simulacion_ajustado,
    DROP CONSTRAINT IF EXISTS ck_simulacion_permitido,
    DROP COLUMN tipo_obra,
    DROP COLUMN caudal_pico,
    DROP COLUMN distancia_m,
    DROP COLUMN eficiencia,
    DROP COLUMN retencion,
    DROP COLUMN caudal_ajustado,
    DROP COLUMN caudal_permitido,
    DROP COLUMN dentro_de_capacidad,
    ADD CONSTRAINT ck_simulacion_latitud  CHECK (latitud  BETWEEN -90  AND 90),
    ADD CONSTRAINT ck_simulacion_longitud CHECK (longitud BETWEEN -180 AND 180);

-- 4. alcaldia ------------------------------------------------------------------
ALTER TABLE alcaldia DROP CONSTRAINT IF EXISTS ck_alcaldia_absorcion, DROP COLUMN porcentaje_absorcion;

-- 5. Ingenieros que trabajan un mismo proyecto -------------------------------------
CREATE TABLE proyecto_ingeniero (
    id_proyecto   INTEGER      NOT NULL,
    id_usuario    INTEGER      NOT NULL,
    fecha_union   TIMESTAMP(0) NOT NULL DEFAULT LOCALTIMESTAMP(0),
    PRIMARY KEY (id_proyecto, id_usuario),
    CONSTRAINT fk_miembro_proyecto FOREIGN KEY (id_proyecto) REFERENCES proyecto (id_proyecto) ON DELETE CASCADE,
    CONSTRAINT fk_miembro_usuario  FOREIGN KEY (id_usuario)  REFERENCES usuario (id_usuario) ON DELETE CASCADE
);
CREATE INDEX idx_miembro_usuario ON proyecto_ingeniero (id_usuario);

-- Seguridad de Supabase en las tablas nuevas (igual que en las demás).
ALTER TABLE tipo_incidencia    ENABLE ROW LEVEL SECURITY;
ALTER TABLE nivel_agua         ENABLE ROW LEVEL SECURITY;
ALTER TABLE tipo_obra          ENABLE ROW LEVEL SECURITY;
ALTER TABLE proyecto_ingeniero ENABLE ROW LEVEL SECURITY;

COMMIT;
