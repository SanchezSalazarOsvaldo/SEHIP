-- Las incidencias oficiales se cargan aprobadas; las que reportan los ciudadanos desde la app móvil
-- entran como 'Pendiente' y solo se muestran en los mapas cuando un administrador las aprueba.
CREATE TABLE punto_critico (
    id_punto            INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_alcaldia         SMALLINT     NOT NULL,
    latitud             NUMERIC(9,6) NOT NULL,           -- NUMERIC(9,6) = -90.000000 a 90.000000; 9 dígitos totales, 6 decimales
    longitud            NUMERIC(9,6) NOT NULL,          
    fecha_registro      TIMESTAMP(0) NOT NULL DEFAULT LOCALTIMESTAMP(0),  -- TIMESTAMP(0) = YYYY-MM-DD HH:MM:SS sin decimales; LOCALTIMESTAMP(0) = hora local del servidor
    origen              VARCHAR(10)  NOT NULL DEFAULT 'Oficial',          -- Oficial o Ciudadano
    estado              VARCHAR(10)  NOT NULL DEFAULT 'Aprobada',         -- Pendiente o Aprobada
    id_tipo_incidencia  SMALLINT     NOT NULL,
    id_nivel_agua       SMALLINT     NULL,                                -- NULL = sin nivel registrado
    descripcion         VARCHAR(200) NULL,
    CONSTRAINT fk_punto_alcaldia FOREIGN KEY (id_alcaldia) REFERENCES alcaldia (id_alcaldia),
    CONSTRAINT fk_punto_tipo  FOREIGN KEY (id_tipo_incidencia) REFERENCES tipo_incidencia (id_tipo_incidencia),
    CONSTRAINT fk_punto_nivel FOREIGN KEY (id_nivel_agua) REFERENCES nivel_agua (id_nivel_agua),
    CONSTRAINT ck_punto_latitud  CHECK (latitud  BETWEEN -90  AND 90),
    CONSTRAINT ck_punto_longitud CHECK (longitud BETWEEN -180 AND 180),
    CONSTRAINT ck_punto_origen CHECK (origen IN ('Oficial', 'Ciudadano')),
    CONSTRAINT ck_punto_estado CHECK (estado IN ('Pendiente', 'Aprobada'))
);
-- RF-MOV-05: hasta 100 puntos por alcaldía, del registro más reciente al más antiguo.
CREATE INDEX idx_punto_alcaldia_fecha ON punto_critico (id_alcaldia, fecha_registro DESC);

-- ---------------------------------------------------------------------
-- TABLA MAESTRA NORMATIVA (RF-ADM-03)
-- Una fila existe solo cuando el administrador ya capturó el valor; si no hay fila, el valor está
-- pendiente. Al capturarlo de nuevo se sobrescribe sin conservar el anterior.
-- ---------------------------------------------------------------------
CREATE TABLE coeficiente_normativo (
    tipo   VARCHAR(2)   PRIMARY KEY,   -- Cp: superficie permeable, Ci: impermeable
    valor  NUMERIC(3,2) NOT NULL,      -- 0.05 a 0.95
    CONSTRAINT ck_coeficiente_tipo  CHECK (tipo IN ('Cp', 'Ci')),
    CONSTRAINT ck_coeficiente_valor CHECK (valor BETWEEN 0.05 AND 0.95)
);

CREATE TABLE intensidad_lluvia (
    id_alcaldia      SMALLINT     NOT NULL,
    periodo_retorno  SMALLINT     NOT NULL,      -- años: 2, 5, 10, 20 o 50
    intensidad_mm_h  NUMERIC(5,2) NOT NULL,      -- 10.00 a 250.00
    PRIMARY KEY (id_alcaldia, periodo_retorno),
    CONSTRAINT fk_intensidad_alcaldia FOREIGN KEY (id_alcaldia) REFERENCES alcaldia (id_alcaldia),
    CONSTRAINT ck_intensidad_periodo CHECK (periodo_retorno IN (2, 5, 10, 20, 50)),
    CONSTRAINT ck_intensidad_valor   CHECK (intensidad_mm_h BETWEEN 10.00 AND 250.00)
);

-- ---------------------------------------------------------------------
-- PROYECTOS Y SIMULACIONES (módulo web de simulación hidrológica)
-- Solo se guardan los datos que captura el ingeniero. Los resultados se calculan al consultar:
--   superficie total = permeable + impermeable
--   coeficiente C    = (Cp · Ap + Ci · Ai) / (Ap + Ai), con Cp y Ci de coeficiente_normativo
--   intensidad       = intensidad_lluvia de (id_alcaldia, periodo_retorno)
--   caudal pico      = C · I · A / 360 (cuando el estado es 'Calculado')
-- Así un cambio en la tabla maestra (RF-ADM-03) se refleja en todos los proyectos sin datos repetidos.
-- ---------------------------------------------------------------------
CREATE TABLE proyecto (
    id_proyecto            INTEGER       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,   -- entero único >= 1
    id_usuario             INTEGER       NOT NULL,                  -- creador (dueño) del proyecto
    nombre                 VARCHAR(100)  NOT NULL,                  -- 1 a 100 caracteres; admite repetidos
    id_alcaldia            SMALLINT      NOT NULL,
    latitud                NUMERIC(9,6)  NOT NULL,                  -- punto de ubicación en el mapa
    longitud               NUMERIC(9,6)  NOT NULL,
    fecha_creacion         DATE          NOT NULL DEFAULT CURRENT_DATE,   -- YYYY-MM-DD
    estado                 VARCHAR(10)   NOT NULL DEFAULT 'En proceso',   -- 'Calculado' tras RF-WEB-06
    superficie_permeable   NUMERIC(9,2)  NULL,                      -- m², 0.00 a 1,000,000.00 (RF-WEB-04)
    superficie_impermeable NUMERIC(9,2)  NULL,                      -- m², 0.00 a 1,000,000.00
    periodo_retorno        SMALLINT      NULL,                      -- 2, 5, 10, 20 o 50 años (RF-WEB-05)
    CONSTRAINT fk_proyecto_usuario  FOREIGN KEY (id_usuario)  REFERENCES usuario (id_usuario),
    CONSTRAINT fk_proyecto_alcaldia FOREIGN KEY (id_alcaldia) REFERENCES alcaldia (id_alcaldia),
    -- La intensidad del proyecto es la de su alcaldía y período de retorno (llave compuesta).
    -- Una llave compuesta es una llave primaria o foránea que consta de dos o más columnas, y se usa para garantizar la unicidad de los registros en la tabla relacionada.
    CONSTRAINT fk_proyecto_intensidad FOREIGN KEY (id_alcaldia, periodo_retorno)
        REFERENCES intensidad_lluvia (id_alcaldia, periodo_retorno),
    CONSTRAINT ck_proyecto_nombre CHECK (CHAR_LENGTH(nombre) BETWEEN 1 AND 100),
    CONSTRAINT ck_proyecto_estado_valor CHECK (estado IN ('En proceso', 'Calculado')),
    CONSTRAINT ck_proyecto_latitud  CHECK (latitud  BETWEEN -90  AND 90),
    CONSTRAINT ck_proyecto_longitud CHECK (longitud BETWEEN -180 AND 180),
    CONSTRAINT ck_proyecto_superficies CHECK (
        (superficie_permeable IS NULL AND superficie_impermeable IS NULL)
        OR (superficie_permeable BETWEEN 0 AND 1000000 AND superficie_impermeable BETWEEN 0 AND 1000000
            AND superficie_permeable + superficie_impermeable BETWEEN 0.01 AND 1000000)),
    CONSTRAINT ck_proyecto_periodo CHECK (periodo_retorno IS NULL OR periodo_retorno IN (2, 5, 10, 20, 50)),
    CONSTRAINT ck_proyecto_estado CHECK (
        estado = 'En proceso' OR (superficie_permeable IS NOT NULL AND periodo_retorno IS NOT NULL))
);
-- RF-WEB-03: historial paginado por usuario, fecha de creación descendente.
CREATE INDEX idx_proyecto_historial ON proyecto (id_usuario, fecha_creacion DESC, id_proyecto DESC);
CREATE INDEX idx_proyecto_alcaldia ON proyecto (id_alcaldia);

-- Ingenieros invitados por el creador para trabajar el mismo proyecto (relación muchos a muchos entre
