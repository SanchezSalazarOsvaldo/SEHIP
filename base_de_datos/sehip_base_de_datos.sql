--   rol, usuario ............................ cuentas || asociadas a (RF-WEB-01, RF-ADM-01 y RF-ADM-04 a 10)
--   administrador_inicial ................... la cuenta de administrador que no se puede borrar
--   alcaldia ................................ asociada a RF-WEB-02, RF-MOV-04
--   coeficiente_normativo ................... asociada a RF-WEB-04, RF-WEB-07, RF-ADM-03 (Cp y Ci)
--   intensidad_lluvia ....................... asociada a RF-WEB-05, RF-ADM-03, RF-MOV-04
--   tipo_incidencia, nivel_agua ............. catálogos de las incidencias
--   punto_critico ........................... asociada a RF-MOV-05, RF-MOV-10, RF-ADM-02, RF-ADM-11 y 12
--   proyecto ................................ asociada a RF-WEB-02 a 06, RF-WEB-08 (datos de entrada del cálculo)
