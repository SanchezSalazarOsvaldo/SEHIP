CREATE TABLE proyecto_ingeniero (
    id_proyecto   INTEGER  NOT NULL,
    id_usuario    INTEGER  NOT NULL,
    PRIMARY KEY (id_proyecto, id_usuario),
    CONSTRAINT fk_miembro_proyecto FOREIGN KEY (id_proyecto) REFERENCES proyecto (id_proyecto) ON DELETE CASCADE, -- Restriccion para que al eliminar un proyecto se eliminen todos los ingenieros invitados a ese proyecto.
    CONSTRAINT fk_miembro_usuario  FOREIGN KEY (id_usuario)  REFERENCES usuario (id_usuario) ON DELETE CASCADE
);
CREATE INDEX idx_miembro_usuario ON proyecto_ingeniero (id_usuario);

CREATE TABLE tipo_obra (
