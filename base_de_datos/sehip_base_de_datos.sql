-- =====================================================================
-- SEHIP - Sistema de Evaluación Hidrológica e Impacto Pluvial
-- Base de datos completa (PostgreSQL 15 o superior, compatible con Supabase) - Equipo 3
--   * Cada tabla guarda solo datos que dependen de su llave completa.
--   * Lo que se puede calcular no se guarda: superficie total, coeficiente C, intensidad del proyecto,
--     caudales, eficiencias, tamaño y nombre del archivo PDF para evitar duplicados.
--   * Sin columnas que casi siempre quedan vacías: el administrador inicial vive en su propia tabla y
--     los códigos de recuperación de contraseña son temporales, por lo que viven en la sesión.
--   * Los valores normativos solo existen cuando ya se capturaron (sin filas con NULL).
--
-- Instrucciones para ejecutar en Supabase: SQL Editor > New query > pegar todo este archivo > Run.
-- Después ejecutar datos_prueba.sql de la misma forma.
--
