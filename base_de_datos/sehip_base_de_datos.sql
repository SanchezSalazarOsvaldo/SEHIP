--   tipo_obra ............................... catálogo de obras de mitigación
--   simulacion_mitigacion ................... asociada a RF-WEB-07, RF-ADM-02
--   reporte_pdf ............................. asociada a RF-WEB-08 (el PDF se guarda dentro de la tabla)
--   sesion .................................. sesiones abiertas del servidor web
