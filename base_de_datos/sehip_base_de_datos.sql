CREATE TABLE rol (
    id_rol  SMALLINT    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- SMALLINT = 0 a 32,767 2 bytes; suficiente para los dos roles iniciales y los que se agreguen en el futuro
    -- GENERATED BY DEFAULT AS IDENTITY funciona como un AUTO_INCREMENT
    nombre  VARCHAR(30) NOT NULL,
CONSTRAINT uq_rol_nombre UNIQUE (nombre) -- CONSTRAINT uq_rol_nombre UNIQUE (nombre) asegura que no haya dos roles con el mismo nombre.
);

CREATE TABLE usuario (
    id_usuario               INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- INTEGER = 0 a 2,147,483,647 4 bytes; suficiente para los usuarios que se creen en el futuro
    nombre                   VARCHAR(100) NOT NULL,                -- 1 a 100 caracteres (RF-ADM-04)
    correo                   VARCHAR(50)  NOT NULL,                -- 5 a 50 caracteres (RF-WEB-01, RF-ADM-04)
    contrasena_hash          VARCHAR(255) NOT NULL,                -- contraseña cifrada con bcrypt para evitar vulnerabilidades (RF-ADM-04)
    id_rol                   SMALLINT     NOT NULL,
    activo                   BOOLEAN      NOT NULL DEFAULT TRUE,   -- FALSE = cuenta inactiva (RF-ADM-07)
    debe_cambiar_contrasena  BOOLEAN      NOT NULL DEFAULT FALSE,  -- TRUE = contraseña temporal sin cambiar
    CONSTRAINT fk_usuario_rol FOREIGN KEY (id_rol) REFERENCES rol (id_rol),
    CONSTRAINT ck_usuario_nombre CHECK (CHAR_LENGTH(nombre) BETWEEN 1 AND 100),
    CONSTRAINT ck_usuario_correo CHECK (CHAR_LENGTH(correo) BETWEEN 5 AND 50) -- CHECK para verificar una condición en la columna que corresponda.
);
-- El correo es único sin distinguir mayúsculas y minúsculas.
CREATE UNIQUE INDEX uq_usuario_correo ON usuario (LOWER(correo)); -- UNIQUE INDEX en lugar de INDEX para garantizar que no haya dos usuarios con el mismo correo electrónico, sin importar si se escriben en mayúsculas o minúsculas.
CREATE INDEX idx_usuario_nombre ON usuario (nombre); -- INDEX es un índice que mejora el rendimiento de las consultas que buscan por un dato.
CREATE INDEX idx_usuario_rol ON usuario (id_rol);

-- Cuenta del administrador inicial: la primera cuenta de administrador, que crea a las demás y que nunca
-- se puede eliminar, desactivar ni cambiar de rol. Es una sola fila; guardarla aparte evita una columna
-- que sería FALSE en todas las demás cuentas.
CREATE TABLE administrador_inicial (
    id_usuario  INTEGER  PRIMARY KEY,
    CONSTRAINT fk_admin_inicial_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario)
);
-- Índice único sobre una constante: la tabla admite como máximo una fila.
CREATE UNIQUE INDEX uq_un_administrador_inicial ON administrador_inicial ((TRUE));

