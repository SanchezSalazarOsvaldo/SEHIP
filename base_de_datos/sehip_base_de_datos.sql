-- ---------------------------------------------------------------------
-- ADMINISTRADOR INICIAL PROTEGIDO
-- Debe existir siempre un administrador que cree las demás cuentas. El administrador inicial (la
-- cuenta registrada en administrador_inicial) no se puede eliminar, deshabilitar, degradar de rol ni
-- duplicar; sí se pueden modificar su nombre, correo y contraseña. Las reglas viven en la base de
-- datos para que ningún módulo (ni un error de programación) pueda saltárselas:
--   * Eliminarlo lo impide la llave foránea de administrador_inicial (no tiene ON DELETE CASCADE).
--   * Duplicarlo lo impide el índice único uq_un_administrador_inicial.
--   * Desactivarlo o cambiarle el rol lo impide fn_proteger_administrador_inicial.
--   * Quitarle la protección o pasarla a otra cuenta lo impide fn_administrador_inicial_fijo.
-- ---------------------------------------------------------------------
CREATE FUNCTION fn_proteger_administrador_inicial() RETURNS TRIGGER -- Un trigger no es más que una restriccion especial que se ejecuta automáticamente antes o después de una operación de inserción, actualización o eliminación en una tabla. En este caso, el trigger se ejecuta antes de actualizar la tabla usuario.
LANGUAGE plpgsql AS $$ -- plpgsql = Procedural Language/PostgreSQL; permite escribir funciones y triggers con lógica de programación, como condicionales y bucles.
BEGIN -- Aqui no es necesario especificar el tipo de operación que se está realizando (INSERT, UPDATE o DELETE) porque el trigger solo se ejecuta antes de una actualización (BEFORE UPDATE).
    IF EXISTS (SELECT 1 FROM administrador_inicial WHERE id_usuario = OLD.id_usuario) THEN -- NEW y OLD son registros especiales que representan los valores de la fila antes y después de la operación. En este caso, se verifica si la fila que se está actualizando es la del administrador inicial.
        IF NOT NEW.activo THEN
            RAISE EXCEPTION 'El administrador inicial no puede deshabilitarse.';
        END IF;
        IF NEW.id_rol <> OLD.id_rol THEN
            RAISE EXCEPTION 'El administrador inicial no puede cambiar de rol.';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_usuario_antes_actualizar BEFORE UPDATE ON usuario
    FOR EACH ROW EXECUTE FUNCTION fn_proteger_administrador_inicial(); -- FOR EACH ROW = el trigger se ejecuta para cada fila afectada por la operación de actualización. En este caso, se ejecuta para cada fila de la tabla usuario que se está actualizando.

-- La fila de administrador_inicial solo se agrega una vez, para una cuenta activa con rol de
-- administrador, y después ya no cambia ni se borra.
CREATE FUNCTION fn_administrador_inicial_fijo() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN -- Aqui es necesario especificar el tipo de operación que se está realizando (INSERT, UPDATE o DELETE) para que la función pueda validar correctamente la operación y lanzar una excepción si no se cumple la condición.
        IF NOT EXISTS (SELECT 1 FROM usuario u JOIN rol r ON r.id_rol = u.id_rol -- Esto asegura que la cuenta que se está insertando como administrador inicial sea una cuenta activa de administrador.
                        WHERE u.id_usuario = NEW.id_usuario AND u.activo
                          AND r.nombre = 'Administrador del Sistema') THEN
            RAISE EXCEPTION 'El administrador inicial debe ser una cuenta activa de administrador.';
        END IF;
        RETURN NEW;
    END IF;
    RAISE EXCEPTION 'No se puede quitar ni cambiar la protección del administrador inicial.';
END;
$$;

CREATE TRIGGER trg_admin_inicial_insertar BEFORE INSERT ON administrador_inicial
    FOR EACH ROW EXECUTE FUNCTION fn_administrador_inicial_fijo();
CREATE TRIGGER trg_admin_inicial_cambiar BEFORE UPDATE OR DELETE ON administrador_inicial
    FOR EACH ROW EXECUTE FUNCTION fn_administrador_inicial_fijo();

